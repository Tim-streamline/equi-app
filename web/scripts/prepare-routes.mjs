import { readdir, mkdir, readFile, writeFile, rename, rm } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const source = path.resolve(root, '../expo-app/app');
const target = path.join(root, 'app');
const generatedHeader = '// Generated by prepare-routes.mjs. Edit the shared Expo route.\n';

export async function prepareRoutes({ source, target, root }) {
  const expected = new Set();
  async function visit(directory = '') {
    for (const entry of await readdir(path.join(source, directory), { withFileTypes: true })) {
      const relative = path.join(directory, entry.name);
      if (entry.isDirectory()) { await visit(relative); continue; }
      if (!/\.[jt]sx?$/.test(entry.name)) continue;
      const destination = path.join(target, relative);
      expected.add(relative);
      const implementation = relative === '_layout.tsx' ? path.join(root, 'components/RootLayout.tsx') : path.join(source, relative);
      let specifier = path.relative(path.dirname(destination), implementation).replaceAll(path.sep, '/').replace(/\.[jt]sx?$/, '');
      if (!specifier.startsWith('.')) specifier = './' + specifier;
      const contents = `${generatedHeader}export { default } from ${JSON.stringify(specifier)};\nexport * from ${JSON.stringify(specifier)};\n`;
      const existing = await readFile(destination, 'utf8').catch(error => {
        if (error.code !== 'ENOENT') throw error;
        return null;
      });
      // Metro watches this directory. Unchanged wrappers must keep their identity:
      // deleting/recreating the tree while it runs can invalidate its route graph.
      if (existing === contents) continue;
      await mkdir(path.dirname(destination), { recursive: true });
      const temporary = `${destination}.${randomUUID()}.tmp`;
      try {
        await writeFile(temporary, contents);
        await rename(temporary, destination);
      } finally {
        await rm(temporary, { force: true });
      }
    }
  }
  await visit();

  async function removeStale(directory = '') {
    for (const entry of await readdir(path.join(target, directory), { withFileTypes: true })) {
      const relative = path.join(directory, entry.name);
      if (entry.isDirectory()) { await removeStale(relative); continue; }
      if (!entry.isFile() || !/\.[jt]sx?$/.test(entry.name) || expected.has(relative)) continue;
      const destination = path.join(target, relative);
      if ((await readFile(destination, 'utf8')).startsWith(generatedHeader)) await rm(destination);
    }
  }
  await mkdir(target, { recursive: true });
  await removeStale();
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await prepareRoutes({ source, target, root });
}
